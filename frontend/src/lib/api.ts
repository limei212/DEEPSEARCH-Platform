import { API_BASE_URL } from "./config";
import type { CancelTaskResponse, FileListResponse, TaskResponse, UploadResponse, SavedTask } from "../types";
import type { SidebarTask } from './taskHistory';

function apiUrl(path: string): string {
  return `${API_BASE_URL}${path}`;
}

async function requestJson<T>(input: RequestInfo | URL, init?: RequestInit): Promise<T> {
  const response = await fetch(input, init);
  const contentType = response.headers.get("content-type") || "";
  const payload = contentType.includes("application/json")
    ? await response.json()
    : await response.text();

  if (!response.ok) {
    const message =
      typeof payload === "object" && payload && "detail" in payload
        ? String(payload.detail)
        : `HTTP ${response.status}`;
    throw new Error(message);
  }

  return payload as T;
}

export async function startTask(query: string, threadId: string, taskId?: string): Promise<TaskResponse> {
  return requestJson<TaskResponse>(apiUrl("/api/task"), {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      query,
      thread_id: threadId,
      task_id: taskId
    })
  });
}

export function listTaskHistory(before?: number): Promise<{tasks:SidebarTask[];next_cursor:number|null}> {
  return requestJson(apiUrl('/api/tasks'+(before?`?before=${before}`:'')));
}

export function getSavedTask(id: string): Promise<SavedTask> {
  return requestJson(apiUrl('/api/tasks/'+encodeURIComponent(id)));
}

export function listUploadedFiles(threadId:string):Promise<{files:{name:string;size:number}[]}> {
  return requestJson(apiUrl('/api/uploads/'+encodeURIComponent(threadId)));
}

export async function cancelTask(threadId: string): Promise<CancelTaskResponse> {
  return requestJson<CancelTaskResponse>(apiUrl(`/api/task/${encodeURIComponent(threadId)}/cancel`), {
    method: "POST"
  });
}

export async function uploadSessionFiles(
  files: File[],
  threadId: string
): Promise<UploadResponse> {
  const formData = new FormData();
  formData.append("thread_id", threadId);
  files.forEach((file) => formData.append("files", file));

  return requestJson<UploadResponse>(apiUrl("/api/upload"), {
    method: "POST",
    body: formData
  });
}

export async function listSessionFiles(path: string): Promise<FileListResponse> {
  const url = new URL(apiUrl("/api/files"));
  url.searchParams.set("path", path);
  return requestJson<FileListResponse>(url);
}

export function getDownloadUrl(path: string): string {
  const url = new URL(apiUrl("/api/download"));
  url.searchParams.set("path", path);
  return url.toString();
}
